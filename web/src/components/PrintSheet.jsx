'use client';

import { useEffect, useState } from 'react';
import { createPortal } from 'react-dom';

/* ══════════════════════════════════════════════════
   میزبانِ چاپ — چیزی که واقعاً روی کاغذ می‌رود.

   ── چه چیزی را درست می‌کند ──
   نسخهٔ پیشین رسید را با `visibility: hidden` روی
   `body *` چاپ می‌کرد و فقط کشوی سبد را برمی‌گرداند.
   مشکلش این است که `visibility` عنصر را از **چیدمان**
   حذف نمی‌کند: کل فروشگاه — هدر، سه فهرست کالا، کارت‌ها
   و تصویرهای SVGشان، متن‌ها و فوتر — همچنان ارتفاع
   واقعیِ خودشان را داشتند و مرورگر همان ارتفاع را
   صفحه‌بندی می‌کرد. نتیجه اندازه‌گیری شد: ۳۳ صفحه، که
   ۳۱ تای آخرش کاغذ سفیدِ خالی بود.

   `display: none` این را حل می‌کند، ولی نمی‌شود مستقیم
   روی نیاکانِ رسید زدش — رسید چند لایه داخل درخت است و
   پنهان‌کردنِ هر نیایی خودش را هم می‌برد.

   ── راه‌حل ──
   رسید یک بار دیگر، این بار به‌شکل فرزندِ **مستقیمِ**
   body، از راه portal رندر می‌شود. آن‌وقت قاعدهٔ چاپ یک
   خط است: «هر فرزند body به‌جز این یکی، display:none».
   هیچ ردی از صفحه روی کاغذ نمی‌ماند و ارتفاع سند دقیقاً
   ارتفاع خودِ رسید است.

   روی صحنه این میزبان `display: none` است و
   `aria-hidden` دارد، پس نه دیده می‌شود نه صفحه‌خوان دو
   بار می‌خواندش. همان کامپوننت رسید در هر دو جا رندر
   می‌شود، پس یک منبع حقیقت بیشتر نیست.

   ── چرا صبر برای mount ──
   portal به `document` نیاز دارد و روی سرور چنین چیزی
   نیست. تا وقتی mount نشده هیچ چیزی برنمی‌گرداند، پس
   HTML سرور و اولین رندر مرورگر یکی‌اند و hydrate
   شکایتی ندارد.
   ══════════════════════════════════════════════════ */

/* نشانه‌ای روی body که قاعدهٔ چاپ به آن گره خورده.

   بدون این، «هر فرزند body به‌جز میزبان را بردار» روی
   **هر** صفحه‌ای اجرا می‌شد و Ctrl+P روی فروشگاه یک برگ
   سفید می‌داد. با این نشانه، آن قاعده فقط وقتی زنده است
   که واقعاً رسیدی برای چاپ وجود داشته باشد. */
const FLAG = 'has-print-sheet';

export default function PrintSheet({ children }) {
  const [ready, setReady] = useState(false);

  useEffect(() => {
    setReady(true);
    document.body.classList.add(FLAG);
    return () => document.body.classList.remove(FLAG);
  }, []);

  if (!ready) return null;

  return createPortal(
    <div className="print-sheet" aria-hidden="true">
      {children}
    </div>,
    document.body
  );
}
