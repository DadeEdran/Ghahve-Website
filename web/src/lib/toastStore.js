/* ══════════════════════════════════════════════════
   پیام کوتاه («توست») — یک انباره برای کل صفحه.

   ── چرا از ShopContext بیرون آمد ──
   توست هیچ‌وقت واقعاً حالتِ فروشگاه نبود؛ فقط آنجا زندگی
   می‌کرد چون اولین صداکننده‌اش سبد بود. این یک مرز غلط
   بود و مودالِ کالا رویش گیر کرد: مودال در شکافِ @modal
   رندر می‌شود، یعنی **بیرون** از ShopProvider صفحه
   (دلیلش پای app/_item/ItemModal.jsx). پس هر چیزی داخل
   مودال که بخواهد «شد» بگوید، به چیزی نیاز دارد که به
   Provider وابسته نباشد.

   می‌شد Provider دومی دور مودال گذاشت — ولی همان دام
   همیشگی: دو سبد جدا. پس به‌جای بزرگ‌کردنِ کانتکست، این
   یک تکه از آن بیرون آمد.

   ── چرا انبارهٔ ماژولی و نه کانتکستِ دوم ──
   توست یک چیز است در کل صفحه، نه یک چیز به‌ازای هر
   زیردرخت. با انبارهٔ ماژولی + useSyncExternalStore هر
   کامپوننتی — در هر شکافی از درخت — می‌تواند پیام بدهد
   و همان یک نوار پایین صفحه نشانش می‌دهد.

   ── روی سرور ──
   toast() فقط از دلِ رویدادهای مرورگر صدا زده می‌شود، پس
   این متغیرها روی سرور هیچ‌وقت پر نمی‌شوند. با این حال
   getServerToast همیشه رشتهٔ خالی می‌دهد تا HTML سرور و
   اولین رندر مرورگر قطعاً یکی باشند.
   ══════════════════════════════════════════════════ */

/* ══════════════════════════════════════════════════
   عمرِ پیام.

   ۲.۶ ثانیه بود — همان عددی که از روز اول مانده بود، از
   وقتی تنها پیام‌ها کوتاه بودند («به سبد اضافه شد»).
   پیام‌های بعدی بلندتر شدند؛ بلندترینشان پیامِ هم‌رسانی
   است: «لینک این کالا کپی شد — حالا می‌توانید بفرستیدش»،
   نزدیک به پنجاه نویسه.

   و آن ۲.۶ ثانیه همه‌اش خواندنی نبود: ۰.۳ ثانیهٔ اولش
   محوِ ورود است (transition روی opacity در style.css)،
   پس عملاً حدود ۲.۳ ثانیه می‌ماند برای خواندنِ جمله‌ای
   که چشم فارسی‌خوان دست‌کم سه ثانیه لازمش دارد. پیام
   می‌آمد و پیش از آنکه خوانده شود می‌رفت.

   ۴.۵ ثانیه یعنی بعد از محوِ ورود، چهار ثانیهٔ کامل روی
   صفحه است. اگر روزی پیام بلندتری اضافه شد، اینجا همان
   جایی است که باید عوض شود — نه در کامپوننت.
   ══════════════════════════════════════════════════ */
export const TOAST_LIFETIME = 4500;

let message = '';
let timer = null;
const listeners = new Set();

const emit = () => {
  for (const listen of listeners) listen();
};

/** پیام را نشان می‌دهد و بعد از TOAST_LIFETIME برش می‌دارد. */
export function toast(msg) {
  message = String(msg ?? '');
  clearTimeout(timer);
  /* پیام تازه، شمارشِ تازه — دو کلیک پشت‌سرهم نباید
     دومی را زودتر ببرد. */
  timer = setTimeout(() => {
    message = '';
    timer = null;
    emit();
  }, TOAST_LIFETIME);
  emit();
}

export function subscribeToast(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export const getToast = () => message;

export const getServerToast = () => '';
