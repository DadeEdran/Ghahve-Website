'use client';

import { useCallback } from 'react';
import { useRouter } from 'next/navigation';

/* ══════════════════════════════════════════════════
   «فروشگاه را تازه کن» — جانشینِ reload() در پنل مدیریت.

   ── چه چیزی جایش را گرفت ──
   در نسخهٔ ویت، سه صفحهٔ پنل (کالاها، فرم کالا، محتوای
   سایت) بعد از هر تغییر `useShop().reload()` را صدا
   می‌زدند. دلیلش این بود که ShopContext فهرست کالاها را
   یک بار موقع بالا آمدن سایت می‌گرفت و در حافظه نگه
   می‌داشت؛ بدون آن صدا زدن، مدیر کالایی را عوض می‌کرد و
   فروشگاه همان نسخهٔ کهنه را نشان می‌داد.

   در Next آن حافظه وجود ندارد: هر صفحهٔ فروشگاه در هر
   درخواست از نو روی سرور ساخته می‌شود. ولی یک کشِ دیگر
   هست — **کشِ مسیریابِ سمت مشتری**. اگر مدیر پیش از رفتن
   به پنل صفحهٔ اصلی را دیده باشد، بازگشتش به آن صفحه
   می‌تواند از همان نسخهٔ کش‌شده بیاید، نه از سرور.

   router.refresh() دقیقاً همین را باطل می‌کند. پس شکلِ
   صدا زدن در آن سه فایل دست‌نخورده ماند و فقط موتورش
   عوض شد — و پنل به ShopProvider نیازی پیدا نکرد، که
   یعنی برای پنل هیچ‌وقت فهرست کالاها بی‌جهت خوانده
   نمی‌شود.
   ══════════════════════════════════════════════════ */

export function useStorefrontRefresh() {
  const router = useRouter();
  return useCallback(() => router.refresh(), [router]);
}
