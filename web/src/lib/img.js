/* پسوند برداری — با پرسمان و لنگر هم درست جواب بدهد،
   چون آدرس تصویرِ بخش «دربارهٔ ما» را مدیر دستی
   می‌نویسد و ممکن است ?v=2 هم داشته باشد. */
const VECTOR = /\.svgz?(?:[?#]|$)/i;

export function isVector(src) {
  return VECTOR.test(String(src || ''));
}

/* آدرسی که next/image می‌تواند بهینه‌اش کند: مسیر محلیِ
   همین دامنه و غیربرداری. هر چیز دیگری (آدرس بیرونی که
   مدیر دستی نوشته) خام سرو می‌شود تا صفحه نشکند —
   بهینه‌ساز برای میزبان ثبت‌نشده خطای ۴۰۰ می‌دهد. */
export function isOptimizable(src) {
  const s = String(src || '');
  return s.startsWith('/') && !s.startsWith('//') && !isVector(s);
}
