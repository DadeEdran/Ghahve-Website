'use client';

/* ══════════════════════════════════════════════════
   وقتی سرور نتوانست صفحه را بسازد.

   عملاً یک حالت دارد: Express خاموش است یا پایگاه داده
   جواب نمی‌دهد. مهم است که این با «کالا پیدا نشد» یکی
   نشود — آن ۴۰۴ است و یعنی «چنین کالایی نداریم»، این
   ۵۰۰ است و یعنی «نتوانستیم بپرسیم». اگر خطای شبکه را
   ۴۰۴ نشان می‌دادیم، یک قطعیِ چنددقیقه‌ای می‌توانست
   کالاهای واقعی را از فهرست گوگل بیندازد.

   همان متن و همان کلاس‌های .load-error نسخهٔ ویت، با
   همان دکمهٔ «تلاش دوباره» — که اینجا reset است، یعنی
   رندر دوبارهٔ همین مسیر.

   کامپوننت خطا در Next حتماً باید سمت مشتری باشد.
   ══════════════════════════════════════════════════ */

export default function Error({ error, reset }) {
  return (
    <main className="item-page">
      <div className="wrap">
        <div className="load-error" role="alert">
          <h1>صفحه خوانده نشد</h1>
          <p>{error?.message || 'خطای غیرمنتظره‌ای رخ داد.'}</p>
          <button className="btn btn-primary" onClick={reset}>
            تلاش دوباره
          </button>
        </div>
      </div>
    </main>
  );
}
