import { Vazirmatn, Lalezar } from 'next/font/google';

/* ══════════════════════════════════════════════════
   فونت‌ها — روی همین دامنه، نه از گوگل (مورد ۲۵).

   در نسخهٔ ویت، index.html یک <link> به
   fonts.googleapis.com داشت. دو مشکل داشت: یک دامنهٔ
   سوم در مسیر بحرانیِ رندر، و — که برای مخاطب این
   فروشگاه مهم‌تر است — دامنه‌ای که برای بسیاری از
   کاربران ایرانی کند یا بسته است. نتیجه‌اش صفحه‌ای بود
   که تا تایم‌اوت شدنِ درخواست، با فونت جایگزین دیده
   می‌شد.

   next/font فایل فونت را **موقع build** می‌گیرد و کنار
   بقیهٔ دارایی‌ها می‌گذارد. در زمان اجرا هیچ درخواستی
   به بیرون نمی‌رود، و برای همین در proxy.js توانستیم
   font-src را به 'self' ببندیم.

   نام خانواده‌ای که Next می‌سازد هش‌دار است، پس از راه
   متغیر CSS به استایل‌نامه می‌رسد — همان دو متغیری که
   web/src/style.css استفاده می‌کند.
   ══════════════════════════════════════════════════ */

/* وزیرمتن روی گوگل‌فونتس یک فونت متغیر است، پس وزن
   جداگانه نمی‌گیرد: همان یک فایل همهٔ وزن‌های ۳۰۰ تا
   ۹۰۰ را که استایل‌نامه می‌خواهد پوشش می‌دهد. */
export const vazirmatn = Vazirmatn({
  subsets: ['arabic', 'latin'],
  variable: '--font-vazirmatn',
  display: 'swap'
});

/* لاله‌زار فقط یک وزن دارد و متغیر نیست، پس وزن اجباری
   است. فقط برای تیترهاست. */
export const lalezar = Lalezar({
  subsets: ['arabic', 'latin'],
  weight: '400',
  variable: '--font-lalezar',
  display: 'swap'
});
