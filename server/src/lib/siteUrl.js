/**
 * @param req درخواست Express (فقط protocol و host را می‌خواند)
 * @param env محیط — پارامتر است تا تست محیط واقعی را دست نزند
 */
export function baseUrlFor(req, env = process.env) {
  const configured = String(env.SITE_URL || '').trim();
  if (configured) return configured;

  /* در توسعه SITE_URL معمولاً تنظیم نشده و همین کافی است.
     در تولید حتماً تنظیمش کنید: پشت پراکسی، هدر Host
     چیزی است که مشتری فرستاده، و می‌تواند هر چیزی باشد. */
  return `${req.protocol}://${req.get('host')}`;
}
